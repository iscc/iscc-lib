# /// script
# requires-python = ">=3.10"
# dependencies = []
# ///
"""Generate the C header of shared edge-case vectors for the C and C++ test programs.

Renders the canonical fixture ``crates/iscc-lib/tests/data-edge.json`` into
``crates/iscc-ffi/tests/data_edge_vectors.h``, which both
``crates/iscc-ffi/tests/test_iscc.c`` and ``packages/cpp/tests/test_iscc.cpp`` include,
so the two surfaces run every vector without a JSON parser. The header is valid C99
and C++17: positional aggregate initialisers only, no zero-length arrays.

Each row carries one resolved expectation per surface (``c`` and ``cpp``): ok or error
from the vector's ``outputs``/``error``, overridden by ``except[<surface>]``. Strings
carry an explicit byte length, because a vector may hold an embedded NUL. Every
non-printable or non-ASCII byte is emitted as a 3-digit octal escape: C hex escapes are
greedy and unbounded (``\\xF0`` swallows any hex digit that follows), while octal
escapes stop after 3 digits, so the header stays pure ASCII and parses unambiguously.

The generator fails closed (``SystemExit``) on a section it has no renderer for, an
empty or missing section, an unexpected input arity or type, and an ``except`` key
outside the surface ids. The drift gate ``tests/test_gen_data_edge_vectors.py`` asserts
the tracked header matches a fresh render byte for byte.

Usage:
    uv run --script scripts/gen_data_edge_vectors.py
"""

from __future__ import annotations

import json
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
FIXTURE_PATH = REPO_ROOT / "crates/iscc-lib/tests/data-edge.json"
OUTPUT_PATH = REPO_ROOT / "crates/iscc-ffi/tests/data_edge_vectors.h"

# Surfaces this header resolves expectations for, in row order.
SURFACES = ("c", "cpp")
# Every surface id `except` may name (edge-vectors.md).
SURFACE_IDS = {
    "rust",
    "python",
    "nodejs",
    "wasm",
    "c",
    "cpp",
    "java",
    "go",
    "ruby",
    "dotnet",
    "swift",
    "kotlin",
}
EXPECT_MACROS = {
    "ok": "ISCC_EDGE_OK",
    "error": "ISCC_EDGE_ERROR",
    "skip": "ISCC_EDGE_SKIP",
}

HEADER_PREAMBLE = """\
/* Generated by scripts/gen_data_edge_vectors.py - DO NOT EDIT.
 *
 * Shared edge-case vectors rendered from crates/iscc-lib/tests/data-edge.json
 * for the C FFI test (crates/iscc-ffi/tests/test_iscc.c) and the C++ wrapper
 * test (packages/cpp/tests/test_iscc.cpp). Valid C99 and C++17.
 *
 * Each row carries the resolved expectation for the c and cpp surfaces.
 * Strings carry an explicit byte length (a vector may hold an embedded NUL).
 * Non-printable and non-ASCII bytes are 3-digit octal escapes (never hex: C
 * hex escapes are greedy and unbounded, octal escapes stop after 3 digits).
 * An empty list points at a one-element sentinel array with count 0.
 * Error rows carry zeroed outputs.
 *
 * Regenerate with: uv run --script scripts/gen_data_edge_vectors.py
 */
#ifndef ISCC_DATA_EDGE_VECTORS_H
#define ISCC_DATA_EDGE_VECTORS_H

#include <stddef.h>

#define ISCC_EDGE_OK 0
#define ISCC_EDGE_ERROR 1
#define ISCC_EDGE_SKIP 2

/* A byte string with an explicit length (NULL ptr when unused). */
struct iscc_edge_str {
    const char *ptr;
    size_t len;
};

/* A list of byte strings: parallel item and length arrays. */
struct iscc_edge_list {
    const char *const *items;
    const size_t *lens;
    size_t count;
};

/* iscc_decode: string -> maintype, subtype, version, length index, digest. */
struct iscc_edge_iscc_decode_vector {
    const char *name;
    int c;
    int cpp;
    struct iscc_edge_str input;
    unsigned int maintype;
    unsigned int subtype;
    unsigned int version;
    unsigned int length;
    struct iscc_edge_str digest;
};

/* encode_seq: string list -> bytes. */
struct iscc_edge_encode_seq_vector {
    const char *name;
    int c;
    int cpp;
    struct iscc_edge_list units;
    struct iscc_edge_str seq;
};

/* gen_text_code_v0: string, bits -> iscc. */
struct iscc_edge_gen_text_code_v0_vector {
    const char *name;
    int c;
    int cpp;
    struct iscc_edge_str text;
    unsigned int bits;
    struct iscc_edge_str iscc;
};

/* gen_mixed_code_v0: string list, bits -> iscc. */
struct iscc_edge_gen_mixed_code_v0_vector {
    const char *name;
    int c;
    int cpp;
    struct iscc_edge_list codes;
    unsigned int bits;
    struct iscc_edge_str iscc;
};

/* gen_iscc_code_v0: string list, wide -> iscc. */
struct iscc_edge_gen_iscc_code_v0_vector {
    const char *name;
    int c;
    int cpp;
    struct iscc_edge_list codes;
    int wide;
    struct iscc_edge_str iscc;
};
"""

HEADER_POSTAMBLE = "#endif /* ISCC_DATA_EDGE_VECTORS_H */\n"

NULL_STR = "{0, 0}"


def escape_c_bytes(data: bytes) -> str:
    """Render bytes as the pure-ASCII body of a C string literal.

    Printable ASCII passes through, with double quote, backslash and question mark
    escaped (the last so no trigraph can form); every other byte becomes a 3-digit
    octal escape.
    """
    parts = []
    for byte in data:
        if byte == 0x22:
            parts.append('\\"')
        elif byte == 0x5C:
            parts.append("\\\\")
        elif byte == 0x3F:
            parts.append("\\?")
        elif 0x20 <= byte <= 0x7E:
            parts.append(chr(byte))
        else:
            parts.append(f"\\{byte:03o}")
    return "".join(parts)


def escape_c_string(text: str) -> str:
    """Render text as the pure-ASCII body of a C string literal of its UTF-8 bytes."""
    return escape_c_bytes(text.encode("utf-8"))


def c_str(data: bytes) -> str:
    """Render bytes as an `iscc_edge_str` initialiser carrying the byte length."""
    return f'{{"{escape_c_bytes(data)}", {len(data)}}}'


def fixture_bytes(value: object, where: str) -> bytes:
    """Decode a `bytes:<hex>` fixture value, failing closed on any other form."""
    if not isinstance(value, str) or not value.startswith("bytes:"):
        raise SystemExit(f"{where}: expected a bytes:<hex> value, got {value!r}")
    return bytes.fromhex(value[len("bytes:") :])


def require_str(value: object, where: str) -> str:
    """Return value if it is a string, else fail closed."""
    if not isinstance(value, str):
        raise SystemExit(f"{where}: expected a string, got {value!r}")
    return value


def require_int(value: object, where: str) -> int:
    """Return value if it is a non-negative integer (not a bool), else fail closed."""
    if isinstance(value, bool) or not isinstance(value, int) or value < 0:
        raise SystemExit(f"{where}: expected a non-negative integer, got {value!r}")
    return value


def require_str_list(value: object, where: str) -> list[str]:
    """Return value if it is a list of strings, else fail closed."""
    if not isinstance(value, list):
        raise SystemExit(f"{where}: expected a list of strings, got {value!r}")
    return [require_str(item, where) for item in value]


def require_arity(inputs: object, allowed: tuple[int, ...], where: str) -> list:
    """Return inputs if it is a list whose length is one of `allowed`, else fail closed."""
    if not isinstance(inputs, list) or len(inputs) not in allowed:
        raise SystemExit(f"{where}: unexpected input arity, expected {allowed}")
    return inputs


def expectations(vector: dict, where: str) -> str:
    """Return the `c, cpp` expectation macros, `except` overriding `outputs`/`error`."""
    exceptions = vector.get("except", {})
    if not isinstance(exceptions, dict):
        raise SystemExit(f"{where}: except is not an object")
    for key, value in exceptions.items():
        if key not in SURFACE_IDS:
            raise SystemExit(f"{where}: except names unknown surface {key!r}")
        if value not in ("error", "skip"):
            raise SystemExit(f"{where}: except {key!r} must be error or skip")
    if ("outputs" in vector) == ("error" in vector):
        raise SystemExit(f"{where}: needs exactly one of outputs / error")
    base = "error" if "error" in vector else "ok"
    return ", ".join(EXPECT_MACROS[exceptions.get(s, base)] for s in SURFACES)


def gen_iscc(vector: dict, where: str) -> str:
    """Return the expected `iscc` string initialiser of a gen vector (zeroed on error)."""
    if "error" in vector:
        return NULL_STR
    outputs = vector["outputs"]
    if not isinstance(outputs, dict) or "iscc" not in outputs:
        raise SystemExit(f"{where}: gen outputs must be an object with an iscc key")
    return c_str(require_str(outputs["iscc"], where).encode("utf-8"))


def list_arrays(ident: str, items: list[str]) -> tuple[list[str], str]:
    """Return the static item/length array lines of one list and its initialiser.

    An empty list gets a one-element sentinel so the pointer is never NULL.
    """
    encoded = [item.encode("utf-8") for item in items] or [b""]
    strs = ", ".join(f'"{escape_c_bytes(e)}"' for e in encoded)
    lens = ", ".join(str(len(e)) for e in encoded)
    lines = [
        f"static const char *const {ident}_items[] = {{{strs}}};",
        f"static const size_t {ident}_lens[] = {{{lens}}};",
    ]
    return lines, f"{{{ident}_items, {ident}_lens, {len(items)}}}"


def row_iscc_decode(vector: dict, where: str, ident: str) -> tuple[list[str], str]:
    """Return the list-array lines and fields of one `iscc_decode` row."""
    (code,) = require_arity(vector["inputs"], (1,), where)
    text = c_str(require_str(code, where).encode("utf-8"))
    if "error" in vector:
        return [], f"{text}, 0, 0, 0, 0, {NULL_STR}"
    outputs = vector["outputs"]
    if not isinstance(outputs, list) or len(outputs) != 5:
        raise SystemExit(f"{where}: iscc_decode outputs must be a 5-element list")
    header = ", ".join(str(require_int(v, where)) for v in outputs[:4])
    return [], f"{text}, {header}, {c_str(fixture_bytes(outputs[4], where))}"


def row_encode_seq(vector: dict, where: str, ident: str) -> tuple[list[str], str]:
    """Return the list-array lines and fields of one `encode_seq` row."""
    (units,) = require_arity(vector["inputs"], (1,), where)
    lines, units_init = list_arrays(ident, require_str_list(units, where))
    if "error" in vector:
        return lines, f"{units_init}, {NULL_STR}"
    return lines, f"{units_init}, {c_str(fixture_bytes(vector['outputs'], where))}"


def row_gen_text_code_v0(vector: dict, where: str, ident: str) -> tuple[list[str], str]:
    """Return the list-array lines and fields of one `gen_text_code_v0` row."""
    text, bits = require_arity(vector["inputs"], (2,), where)
    text_init = c_str(require_str(text, where).encode("utf-8"))
    return [], f"{text_init}, {require_int(bits, where)}, {gen_iscc(vector, where)}"


def row_gen_mixed_code_v0(
    vector: dict, where: str, ident: str
) -> tuple[list[str], str]:
    """Return the list-array lines and fields of one `gen_mixed_code_v0` row."""
    codes, bits = require_arity(vector["inputs"], (2,), where)
    lines, codes_init = list_arrays(ident, require_str_list(codes, where))
    return lines, f"{codes_init}, {require_int(bits, where)}, {gen_iscc(vector, where)}"


def row_gen_iscc_code_v0(vector: dict, where: str, ident: str) -> tuple[list[str], str]:
    """Return the list-array lines and fields of one `gen_iscc_code_v0` row."""
    inputs = require_arity(vector["inputs"], (1, 2), where)
    lines, codes_init = list_arrays(ident, require_str_list(inputs[0], where))
    wide = inputs[1] if len(inputs) == 2 else False
    if not isinstance(wide, bool):
        raise SystemExit(f"{where}: wide must be a boolean, got {wide!r}")
    return lines, f"{codes_init}, {int(wide)}, {gen_iscc(vector, where)}"


# Section name -> row renderer; the section order is the header order.
RENDERERS = {
    "iscc_decode": row_iscc_decode,
    "encode_seq": row_encode_seq,
    "gen_text_code_v0": row_gen_text_code_v0,
    "gen_mixed_code_v0": row_gen_mixed_code_v0,
    "gen_iscc_code_v0": row_gen_iscc_code_v0,
}


def count_macro(section: str) -> str:
    """Return the count macro name of a section."""
    return f"ISCC_EDGE_{section.upper()}_COUNT"


def render_section(section: str, vectors: dict) -> str:
    """Render one fixture section as list arrays, a count macro and a row array."""
    if not isinstance(vectors, dict) or not vectors:
        raise SystemExit(f"fixture section {section!r} is missing or empty")
    arrays: list[str] = []
    rows = []
    for index, (name, vector) in enumerate(vectors.items()):
        where = f"{section}/{name}"
        if not isinstance(vector, dict) or "inputs" not in vector:
            raise SystemExit(f"{where}: vector must be an object with inputs")
        expect = expectations(vector, where)
        ident = f"iscc_edge_{section}_{index}"
        lines, fields = RENDERERS[section](vector, where, ident)
        arrays.extend(lines)
        rows.append(f'    {{"{escape_c_string(name)}", {expect},\n     {fields}}},')
    macro = count_macro(section)
    lines = [*arrays, f"#define {macro} {len(vectors)}"]
    lines.append(
        f"static const struct iscc_edge_{section}_vector iscc_edge_{section}[{macro}] = {{"
    )
    lines.extend(rows)
    lines.append("};")
    return "\n".join(lines) + "\n"


def render(fixture_path: Path) -> str:
    """Render the canonical edge-vector fixture into the full C header text."""
    fixture = json.loads(fixture_path.read_text(encoding="utf-8"))
    unknown = sorted(set(fixture) - set(RENDERERS))
    if unknown:
        raise SystemExit(f"no renderer for fixture section(s) {unknown}")
    blocks = [HEADER_PREAMBLE]
    for section in RENDERERS:
        blocks.append(render_section(section, fixture.get(section)))
    total = sum(len(fixture[section]) for section in RENDERERS)
    blocks.append(f"#define ISCC_EDGE_TOTAL_COUNT {total}\n")
    blocks.append(HEADER_POSTAMBLE)
    header = "\n".join(blocks)
    if not header.isascii():
        raise SystemExit("rendered header is not pure ASCII")
    return header


def main() -> None:
    """Render the fixture and write the tracked C header."""
    header = render(FIXTURE_PATH)
    OUTPUT_PATH.write_text(header, encoding="utf-8", newline="\n")
    print(f"wrote {OUTPUT_PATH}")


if __name__ == "__main__":
    main()
